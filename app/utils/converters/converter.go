package converters

// ------------------------------------------------------------------------------------------------
// Imports
// ------------------------------------------------------------------------------------------------

import "fmt"

// ------------------------------------------------------------------------------------------------
// Services
// ------------------------------------------------------------------------------------------------

// Value to string convertion.
func ToString(v any) string {
	if v == nil {
		return ""
	}
	return fmt.Sprintf("%v", v)
}

// ------------------------------------------------------------------------------------------------

// Boolean to boolean pointer.
// Required by Supertokens.
func ToBoolPointer(b bool) *bool {
	return &b
}

