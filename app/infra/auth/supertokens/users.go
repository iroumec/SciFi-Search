package supertokens

// ------------------------------------------------------------------------------------------------
// Imports
// ------------------------------------------------------------------------------------------------

import "github.com/supertokens/supertokens-golang/supertokens"

// ------------------------------------------------------------------------------------------------
// Services
// ------------------------------------------------------------------------------------------------

func DeleteUser(authID string) error {
	err := supertokens.DeleteUser(authID)

	if err != nil {
		return err
	}

	// User deleted successfully.
	return nil
}

