package languages

// ------------------------------------------------------------------------------------------------
// Imports
// ------------------------------------------------------------------------------------------------

import (
	"golang.org/x/text/language"
	"golang.org/x/text/message"
)

// ------------------------------------------------------------------------------------------------
// Functions
// ------------------------------------------------------------------------------------------------

func registerMessages(tag language.Tag, messages map[string]string) {
	for key, value := range messages {
		message.SetString(tag, key, value)
	}
}

