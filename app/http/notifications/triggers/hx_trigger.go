package triggers

// ------------------------------------------------------------------------------------------------
// Imports
// ------------------------------------------------------------------------------------------------

import "net/http"

// ------------------------------------------------------------------------------------------------
// Services
// ------------------------------------------------------------------------------------------------

func AddHXTrigger(w http.ResponseWriter, r *http.Request, message string) bool {
	if r.Header.Get("HX-Request") == "true" {
		w.Header().Set("HX-Trigger", `{"showFlash": {"message": "`+message+`"}}`)
		return true
	}
	return false
}

